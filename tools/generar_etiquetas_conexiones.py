"""Genera client/src/CadLink.Revit.Nucleo/Conexiones/EtiquetasExcel.g.cs.

El libro de revisiones de acero (NTC-Acero 2023) escribe cada dato en una fila: la etiqueta en la
columna B -«Grueso de la placa, tp =»- y el valor en la C. Las filas se mueven cuando la hoja crece,
asi que CadLink NO lee por fila: lee por etiqueta. Esta tabla dice, hoja por hoja y EN EL ORDEN DE
LA HOJA, que etiqueta lleva cada dato, y el valor de fabrica de cada dato capturable (para saber si
una hoja todavia trae los datos de ejemplo).

La fuente es tools/datos/etiquetas-libro-acero.json, que sale del mismo generador del libro.

    python3 tools/generar_etiquetas_conexiones.py
"""
import json
import os

RAIZ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FUENTE = os.path.join(RAIZ, "tools", "datos", "etiquetas-libro-acero.json")
DESTINO = os.path.join(RAIZ, "client", "src", "CadLink.Revit.Nucleo", "Conexiones", "EtiquetasExcel.g.cs")


def cs(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def defecto(v):
    if v is None:
        return "null"
    if isinstance(v, bool):
        return cs("SI" if v else "NO")
    if isinstance(v, (int, float)):
        return cs(repr(float(v)))
    return cs(v)


def main():
    datos = json.load(open(FUENTE, encoding="utf-8"))
    out = []
    out.append("// <auto-generated>")
    out.append("// Generado por tools/generar_etiquetas_conexiones.py desde tools/datos/etiquetas-libro-acero.json.")
    out.append("// No se edita a mano: se vuelve a generar.")
    out.append("// </auto-generated>")
    out.append("namespace CadLink.Revit.Nucleo;")
    out.append("")
    out.append("/// <summary>Las etiquetas de cada hoja del libro de acero, en el orden de la hoja.</summary>")
    out.append("public static partial class EtiquetasExcel")
    out.append("{")
    out.append("    /// <summary>Clave de la hoja -su codigo-, su nombre, su titulo y sus datos.</summary>")
    out.append("    public static IReadOnlyList<HojaDelLibro> Hojas { get; } = new HojaDelLibro[]")
    out.append("    {")
    for code, h in datos.items():
        out.append("        new(%s, %s, %s, new DatoDelLibro[]" % (cs(code), cs(h["hoja"]), cs(h["titulo"])))
        out.append("        {")
        for nombre, etiqueta, clase, dv in h["items"]:
            out.append("            new(%s, %s, %s, %s)," % (cs(nombre), cs(etiqueta), "true" if clase == "I" else "false", defecto(dv)))
        out.append("        }),")
    out.append("    };")
    out.append("}")
    os.makedirs(os.path.dirname(DESTINO), exist_ok=True)
    with open(DESTINO, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("escrito", os.path.relpath(DESTINO, RAIZ), sum(len(h["items"]) for h in datos.values()), "datos")


if __name__ == "__main__":
    main()
